#!/usr/bin/env python3
"""Generate src/runtime_data.c from runtime/{syntax,colorschemes,help}.

The generated file is checked in, so building the editor needs only a C
compiler.  Run `make runtime` (or this script) after changing runtime files.
Data is emitted as byte arrays rather than string literals so the result
stays within ISO C99 translation limits (-pedantic clean)."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

KINDS = [
    ("syntax", ".yaml", "rt_syntax_files"),
    ("colorschemes", ".micro", "rt_colorscheme_files"),
    ("help", ".md", "rt_help_files"),
]


def main():
    out = ["/* Generated by tools/embed.py -- do not edit. */",
           '#include "runtime.h"', ""]
    for d, ext, table in KINDS:
        path = os.path.join(ROOT, "runtime", d)
        files = sorted(f for f in os.listdir(path) if f.endswith(ext))
        names = []
        for i, f in enumerate(files):
            data = open(os.path.join(path, f), "rb").read() + b"\0"
            var = "%s_%d" % (table, i)
            out.append("static const char %s[] = {" % var)
            for j in range(0, len(data), 24):
                out.append(",".join(str(b if b < 128 else b - 256) for b in data[j:j + 24]) + ",")
            out.append("};")
            names.append((f[: -len(ext)], var))
        out.append("const RtFile %s[] = {" % table)
        for n, v in names:
            out.append('    {"%s", %s},' % (n, v))
        out.append("    {0, 0}")
        out.append("};")
        out.append("")
    with open(os.path.join(ROOT, "src", "runtime_data.c"), "w") as fh:
        fh.write("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
