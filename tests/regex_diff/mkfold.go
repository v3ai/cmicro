// Generates the case-folding table in src/regex.c (fold_tab) from Go's
// unicode.SimpleFold, so that (?i) folds exactly like Go's regexp:
//
//	go run tests/regex_diff/mkfold.go
//
// Each entry {lo, hi, d} means SimpleFold(c) == c + d for lo <= c <= hi;
// d == 0 marks an alternating run (c + 1 for even c - lo, c - 1 for odd).
package main

import (
	"fmt"
	"strings"
	"unicode"
)

type run struct{ lo, hi, d int }

func main() {
	var runs []run
	for r := 0; r <= unicode.MaxRune; r++ {
		f := int(unicode.SimpleFold(rune(r)))
		if f == r {
			continue
		}
		d := f - r
		if n := len(runs); n > 0 {
			l := &runs[n-1]
			if l.hi == r-1 {
				if l.d == d && l.d != 0 {
					l.hi = r
					continue
				}
				// alternating +1/-1 pairs
				want := 1
				if (r-l.lo)%2 == 1 {
					want = -1
				}
				if d == want && (l.d == 0 || (l.lo == l.hi && l.d == 1)) {
					l.d = 0
					l.hi = r
					continue
				}
			}
		}
		runs = append(runs, run{r, r, d})
	}
	var b strings.Builder
	fmt.Fprintf(&b, "/* generated by tests/regex_diff/mkfold.go from Go %s */\n", "unicode.SimpleFold")
	fmt.Fprintf(&b, "static const struct { int lo, hi, d; } fold_tab[] = {\n")
	for i, x := range runs {
		if i%3 == 0 {
			b.WriteString("   ")
		}
		fmt.Fprintf(&b, " {0x%04X, 0x%04X, %d},", x.lo, x.hi, x.d)
		if i%3 == 2 || i == len(runs)-1 {
			b.WriteString("\n")
		}
	}
	b.WriteString("};\n")
	fmt.Print(b.String())
}
