// Generates two tables in src/regex.c from Go's unicode package:
//
//	go run tests/regex_diff/mktables.go
//
// fold_tab, from unicode.SimpleFold, so that (?i) folds exactly like Go's
// regexp; each entry {lo, hi, d} means SimpleFold(c) == c + d for
// lo <= c <= hi, and d == 0 marks an alternating run (c + 1 for even
// c - lo, c - 1 for odd).
//
// unicode_names, the category and script names Go accepts in \p{...}.
package main

import (
	"fmt"
	"sort"
	"strings"
	"unicode"
)

type run struct{ lo, hi, d int }

func main() {
	var runs []run
	for r := 0; r <= unicode.MaxRune; r++ {
		f := int(unicode.SimpleFold(rune(r)))
		if f == r {
			continue
		}
		d := f - r
		if n := len(runs); n > 0 {
			l := &runs[n-1]
			if l.hi == r-1 {
				if l.d == d && l.d != 0 {
					l.hi = r
					continue
				}
				// alternating +1/-1 pairs
				want := 1
				if (r-l.lo)%2 == 1 {
					want = -1
				}
				if d == want && (l.d == 0 || (l.lo == l.hi && l.d == 1)) {
					l.d = 0
					l.hi = r
					continue
				}
			}
		}
		runs = append(runs, run{r, r, d})
	}
	var b strings.Builder
	b.WriteString("/* generated by tests/regex_diff/mktables.go from Go's unicode.SimpleFold */\n")
	b.WriteString("static const struct { int lo, hi, d; } fold_tab[] = {\n")
	for i, x := range runs {
		if i%3 == 0 {
			b.WriteString("   ")
		}
		fmt.Fprintf(&b, " {0x%04X, 0x%04X, %d},", x.lo, x.hi, x.d)
		if i%3 == 2 || i == len(runs)-1 {
			b.WriteString("\n")
		}
	}
	b.WriteString("};\n")

	var names []string
	for n := range unicode.Categories {
		names = append(names, n)
	}
	for n := range unicode.Scripts {
		names = append(names, n)
	}
	names = append(names, "Any")
	sort.Strings(names)
	b.WriteString("\n/* generated by tests/regex_diff/mktables.go: the names Go accepts in \\p{} */\n")
	b.WriteString("static const char *const unicode_names[] = {")
	col := 100
	for _, n := range names {
		item := fmt.Sprintf(" \"%s\",", n)
		if col+len(item) > 96 {
			b.WriteString("\n   ")
			col = 3
		}
		b.WriteString(item)
		col += len(item)
	}
	b.WriteString("\n};\n")
	fmt.Print(b.String())
}
